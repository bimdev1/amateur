"""Round 12a §6: the pre-registered null controls, measured side by side.

Four nulls, each run through the **identical** pipeline (same trigger, organ,
executor, evidence set and gate):

======================  =============================================
null                    construction
======================  =============================================
``zero``                patch factors and bias exactly zero; neutral
                        by construction
``random``              random factors at the fitted norms (same ``K``)
``shuffled``            the standard fit with the fit-window targets
                        permuted along the time axis (same budget/seed)
``no_flip``             the registered environment with no flip at all
                        (``scenario(flip_at=None)``)
======================  =============================================

Every null is measured twice: ``gain_floor="on"`` (the registered
round-12a gate) and ``gain_floor="ablate"`` (the DIAGNOSTIC-ONLY pre-floor
gate).  The pre-registered expectation is **zero promotions for every null
with the floor on**; the ablated run is a secondary diagnostic showing
whether the old gate would have admitted noise.

Nothing here is a gate on the real trace: this module only assembles the
control measurements.  It never steers the live model -- the candidate
patches are shadow-scored by the organ exactly like the registered one.

The committed measurement artifact is generated by::

    python3 -m amateur.physics.nulls --out-dir .work/round12a

which writes ``results.json`` (one top-level key per run) and a short
``RESULTS.md`` table.  ``.work/`` is scratch: the artifact is not committed.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

from .organ import DEFAULT_NULL_SEED, PATCH_MODES
from .run import (
    CONTROL_SEED,
    REGISTERED_SEED,
    PhysicsRun,
)

__all__ = [
    "NULL_NAMES",
    "NULL_PATCH_MODES",
    "gather_results",
    "null_suite",
    "run_null",
    "summarize_run",
    "to_jsonable",
]

#: The null candidate constructions that reuse the registered trigger and
#: scenario (all of them birth at the registered spike, t12).
NULL_PATCH_MODES: tuple[str, ...] = ("zero", "random", "shuffled")
#: Every pre-registered null, including the no-flip control.
NULL_NAMES: tuple[str, ...] = NULL_PATCH_MODES + ("no_flip",)


def _new_run(
    *,
    seed: int,
    gain_floor: str,
    trigger: str,
    patch_mode: str,
    rng_seed: int | None,
) -> PhysicsRun:
    return PhysicsRun(
        seed=seed,
        gain_floor=gain_floor,
        trigger=trigger,
        patch_mode=patch_mode,
        rng_seed=rng_seed,
    )


def summarize_run(run: PhysicsRun, result: Any) -> dict[str, Any]:
    """The full measured record of one run (JSON-able via :func:`to_jsonable`)."""
    summary = result.summary
    record = run._tracked_candidate  # noqa: SLF001 - the run's own record
    evidence = (
        []
        if record is None
        else [tuple(float(value) for value in sample) for sample in record.evidence]
    )
    in_sample = None if record is None else record.in_sample
    adaptation = summary["gates"]["adaptation"]
    admission = summary["gates"]["admission"]
    floor = summary["floor"]
    return {
        "seed": int(run.seed),
        "trigger": run.trigger,
        "gain_floor": run.gain_floor,
        "patch_mode": run.patch_mode,
        "rng_seed": run.rng_seed,
        "births": [list(item) for item in run.births],
        "candidate_fit": dict(summary["candidate_fit"]),
        "candidate_verdict": (
            None if summary["candidate_verdict"] is None
            else dict(summary["candidate_verdict"])
        ),
        "in_sample": None if in_sample is None else list(in_sample),
        "evidence": [list(sample) for sample in evidence],
        "adaptation": dict(adaptation),
        "admission": dict(admission),
        "floor_refusals": [dict(item) for item in floor["refusals"]],
        "qualified_floor_refusals": [
            dict(item) for item in floor["qualified_refusals"]
        ],
        "promotions": [dict(item) for item in admission["promotions"]],
        "residence_curve": [dict(row) for row in summary["residence_curve"]],
        "lifecycle": dict(summary["lifecycle"]),
        "d4": {
            "byte_identical": bool(summary["d4"]["byte_identical"]),
            "retained_byte_identical": bool(
                summary["d4"]["retained_byte_identical"]
            ),
            "sediments": [dict(item) for item in summary["d4"]["sediments"]],
        },
        "end_state": {
            "nursery_ids": list(run.board.nursery_ids()),
            "resident_ids": sorted(run.board.resident_ids()),
            "patches": [
                overlay_id for overlay_id, _patch in run.board.patches()
            ],
            "patch_bytes": int(run.board.patch_bytes()),
            "nursery_patch_bytes": int(run.board.nursery_patch_bytes()),
            "d4_size": len(run.board.d4),
            "encoder_bit_identical": bool(summary["encoder_bit_identical"]),
        },
        "motif_ticks": [
            {"tick": int(row.tick), "motif_id": row.motif_id}
            for row in result.ticks
            if row.motif_id is not None
        ],
        "adoption_ticks": [
            {"tick": int(row.tick), "overlay_id": row.adopted}
            for row in result.ticks
            if row.adopted is not None
        ],
        "tick_sets": {
            key: list(value) for key, value in adaptation["tick_sets"].items()
        },
    }


def run_null(
    name: str,
    *,
    seed: int = REGISTERED_SEED,
    gain_floor: str = "on",
    rng_seed: int | None = DEFAULT_NULL_SEED,
) -> dict[str, Any]:
    """Run one pre-registered null and return its measured record."""
    if name not in NULL_NAMES:
        raise ValueError(
            f"unknown null {name!r}; expected one of {NULL_NAMES}"
        )
    if name in NULL_PATCH_MODES:
        if name not in PATCH_MODES:  # pragma: no cover - organ contract check
            raise AssertionError(f"null {name!r} is not an organ patch mode")
        run = _new_run(
            seed=seed,
            gain_floor=gain_floor,
            trigger="registered",
            patch_mode=name,
            rng_seed=rng_seed,
        )
        result = run.scenario(seed=seed)
    else:  # no_flip
        run = _new_run(
            seed=seed,
            gain_floor=gain_floor,
            trigger="registered",
            patch_mode="fitted",
            rng_seed=rng_seed,
        )
        result = run.scenario(seed=seed, flip_at=None)
    return summarize_run(run, result)


def null_suite(
    *,
    seed: int = REGISTERED_SEED,
    rng_seed: int | None = DEFAULT_NULL_SEED,
) -> dict[str, dict[str, Any]]:
    """All four nulls, each with the floor on and ablated (side by side)."""
    results: dict[str, dict[str, Any]] = {}
    for name in NULL_NAMES:
        results[f"null_{name}"] = run_null(
            name, seed=seed, gain_floor="on", rng_seed=rng_seed
        )
        results[f"null_{name}_ablated"] = run_null(
            name, seed=seed, gain_floor="ablate", rng_seed=rng_seed
        )
    return results


def _run_and_summarize(
    *,
    seed: int,
    gain_floor: str = "on",
    trigger: str = "registered",
    patch_mode: str = "fitted",
    rng_seed: int | None = DEFAULT_NULL_SEED,
) -> dict[str, Any]:
    run = _new_run(
        seed=seed,
        gain_floor=gain_floor,
        trigger=trigger,
        patch_mode=patch_mode,
        rng_seed=rng_seed,
    )
    result = run.scenario(seed=seed)
    return summarize_run(run, result)


def gather_results(
    *,
    seed: int = REGISTERED_SEED,
    rng_seed: int | None = DEFAULT_NULL_SEED,
) -> dict[str, dict[str, Any]]:
    """Every round-12a run: registered, control, historical falsifier, nulls."""
    results: dict[str, dict[str, Any]] = {}
    # 1. The registered trace (prereg §3.5/§4): floor on, registered trigger.
    results["seed7"] = _run_and_summarize(seed=seed, rng_seed=rng_seed)
    # 2a. The new-trigger pre-floor trace (diagnostic; the candidate is
    #     harmful, so it still does not promote -- this is the finding).
    results["seed7_ablated"] = _run_and_summarize(
        seed=seed, gain_floor="ablate", rng_seed=rng_seed
    )
    # 2b. The HISTORICAL falsifier trace: old trigger + ablated floor,
    #     reproducing the Round-11 candidate (birth t19, K=5056, promo t27).
    results["seed7_historical_ablated"] = _run_and_summarize(
        seed=seed,
        gain_floor="ablate",
        trigger="round11",
        rng_seed=rng_seed,
    )
    # 2c. The historical trace under the registered floor: the same
    #     candidate must be refused at the t27 promotion decision.
    results["seed7_historical"] = _run_and_summarize(
        seed=seed, gain_floor="on", trigger="round11", rng_seed=rng_seed
    )
    # 3. The rejection control, floor on and (for the pre-floor record) off.
    results["seed0"] = _run_and_summarize(seed=CONTROL_SEED, rng_seed=rng_seed)
    results["seed0_ablated"] = _run_and_summarize(
        seed=CONTROL_SEED, gain_floor="ablate", rng_seed=rng_seed
    )
    # 4. The null controls, each with the floor on and ablated.
    results.update(null_suite(seed=seed, rng_seed=rng_seed))
    return results


def to_jsonable(value: Any) -> Any:
    """Recursively convert tuples, numpy scalars and non-finite floats."""
    if isinstance(value, dict):
        return {str(key): to_jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [to_jsonable(item) for item in value]
    if isinstance(value, bool):
        return bool(value)
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, (int, str)) or value is None:
        return value
    if hasattr(value, "item"):  # numpy scalar
        return to_jsonable(value.item())
    return str(value)


def _markdown(results: dict[str, dict[str, Any]]) -> str:
    """The short RESULTS.md table the Lead reads (numbers, no narrative)."""
    lines: list[str] = [
        "# Round 12a — measured results (generated by `amateur.physics.nulls`)",
        "",
        "Every number below is a measurement of this round's tree; no round-7..11",
        "number is re-asserted. `primary` is the pre-registered ratio-of-means",
        "ADAPTATION gate; `secondary` is the labelled mean-of-ratios diagnostic.",
        "The falsifier trace (`seed7_historical_ablated`) is a HISTORICAL",
        "DIAGNOSTIC (`trigger=round11`, floor ablated): it reproduces the Round-11",
        "candidate so the registered floor can be applied retroactively.",
        "",
        "| run | trigger | floor | mode | birth | K | ADAPT primary (n) | secondary | with-in-sample (n) | ADMISSION (n/value) | promotions | floor refusals (qual) | D4 sediments |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for key, row in results.items():
        adaptation = row["adaptation"]
        admission = row["admission"]
        fit = row["candidate_fit"]["record"]
        refusals = row["floor_refusals"]
        qualified = row["qualified_floor_refusals"]
        reasons: dict[str, int] = {}
        for item in refusals:
            reasons[str(item["reason"])] = reasons.get(str(item["reason"]), 0) + 1
        reason_text = ", ".join(
            f"{reason}:{count}" for reason, count in sorted(reasons.items())
        ) or "-"
        lines.append(
            "| {key} | {trigger} | {floor} | {mode} | {birth} | {k} | "
            "{primary} ({n}) | {secondary} | {wi} ({wi_n}) | "
            "{adm_n}/{adm_value} | {promos} | {ref_n} ({qual_n}: {reasons}) | "
            "{d4} |".format(
                key=key,
                trigger=row["trigger"],
                floor=row["gain_floor"],
                mode=row["patch_mode"],
                birth=(
                    row["births"][0][1] if row["births"] else "-"
                ),
                k=("-" if fit is None else fit["param_count"]),
                primary=(
                    "-" if adaptation["primary"] is None
                    else f"{adaptation['primary']:.6g}"
                ),
                n=adaptation["n"],
                secondary=(
                    "-" if adaptation["secondary_mean_of_ratios"] is None
                    else f"{adaptation['secondary_mean_of_ratios']:.6g}"
                ),
                wi=(
                    "-" if adaptation["with_in_sample"] is None
                    else f"{adaptation['with_in_sample']:.6g}"
                ),
                wi_n=adaptation["n_with_in_sample"],
                adm_n=admission["n"],
                adm_value=admission["value"],
                promos=len(row["promotions"]),
                ref_n=len(refusals),
                qual_n=len(qualified),
                reasons=reason_text,
                d4=len(row["d4"]["sediments"]),
            )
        )
    lines.extend(
        [
            "",
            "## The retroactive falsifier (prereg §3.5)",
            "",
        ]
    )
    falsifier = results["seed7_historical_ablated"]
    verdict = falsifier["candidate_verdict"]
    if verdict is not None:
        lines.append(
            "Round-11 candidate: birth t{birth}, K={k}; dbar={dbar:.9e}, "
            "gain={gain:.6f} bits, cost={cost:.1f} bits -> admitted={adm}, "
            "reason={reason}. Cost/gain = {ratio:.3g}x. The registered floor "
            "REFUSES it.".format(
                birth=falsifier["births"][0][1],
                k=falsifier["candidate_fit"]["record"]["param_count"],
                dbar=verdict["dbar"],
                gain=verdict["gain_bits"],
                cost=verdict["cost_bits"],
                adm=verdict["admitted"],
                reason=verdict["reason"],
                ratio=(
                    abs(verdict["cost_bits"] / verdict["gain_bits"])
                    if verdict["gain_bits"] else float("inf")
                ),
            )
        )
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Generate the round-12a measurement artifacts (scratch, not committed)."""
    parser = argparse.ArgumentParser(
        description="Run the round-12a registered/control/null measurements."
    )
    parser.add_argument(
        "--out-dir",
        default=".work/round12a",
        help="artifact directory (default: .work/round12a)",
    )
    args = parser.parse_args(argv)
    results = gather_results()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    payload = to_jsonable(results)
    (out_dir / "results.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (out_dir / "RESULTS.md").write_text(_markdown(payload), encoding="utf-8")
    print(f"wrote {out_dir / 'results.json'} and {out_dir / 'RESULTS.md'}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    raise SystemExit(main())
