CORE_DEFS = """
/-- Channel state: mailbox depth plus the scalar charge and accounting
counters. Refused events never materialize as state; refusal is a
charge only, O(1) per channel exactly like a sink. -/
structure St where
  box : Nat
  miss : Nat
  refused : Nat
  sunk : Nat
  used : Nat
  consumed : Nat

/-- Fresh channel with mailbox depth `b`; every counter at zero. -/
def mkSt (b : Nat) : St := ⟨b, 0, 0, 0, 0, 0⟩

theorem mkSt_fields (x : Nat) :
    (mkSt x).box = x ∧ (mkSt x).miss = 0 ∧ (mkSt x).refused = 0
      ∧ (mkSt x).sunk = 0 ∧ (mkSt x).used = 0 ∧ (mkSt x).consumed = 0 :=
  ⟨rfl, rfl, rfl, rfl, rfl, rfl⟩

/-- One admission event, reject-with-charge (adjudicated): emit accepts
onto an empty box and refuses onto a full one; consume drains a
non-empty box and misses on an empty one; deficit (miss) and excess
(refused) are distinct counters that are never added. -/
def applyOp (st : St) : Op -> St
  | .emit =>
      ⟨if st.box = 0 then 1 else st.box, st.miss,
        st.refused + (if st.box = 0 then 0 else 1), st.sunk,
        st.used + (if st.box = 0 then 1 else 0), st.consumed⟩
  | .consume =>
      ⟨if st.box = 0 then st.box else st.box - 1,
        (if st.box = 0 then st.miss + 1 else st.miss), st.refused, st.sunk,
        st.used, if st.box = 0 then st.consumed else st.consumed + 1⟩
  | .sink => ⟨0, st.miss, st.refused, st.sunk + st.box, st.used, st.consumed⟩

/-- Per-op weights: exactly one emit / consume in the corresponding op. -/
def isE : Op → Nat
  | .emit => 1
  | _ => 0

def isC : Op → Nat
  | .consume => 1
  | _ => 0

/-- Number of emit ops in a word. -/
def emitCount : List Op → Nat
  | [] => 0
  | op :: rest => isE op + emitCount rest

/-- Number of consume ops in a word (absorbs compile to consume). -/
def consumeCount : List Op → Nat
  | [] => 0
  | op :: rest => isC op + consumeCount rest

/-- One flow's channel through a word of ops. -/
def flowFold : List Op → St → St
  | [], st => st
  | op :: rest, st => flowFold rest (applyOp st op)

/-- One tick of one flow's channel from depth `x`. -/
def tickFlow (i x : Nat) : St := flowFold (opsOf i) (mkSt x)

/-- Depth accumulator, tick-indexed, from an all-zero start. -/
def bIter : Nat -> Nat -> Nat
  | 0, _ => 0
  | t + 1, i => (tickFlow i (bIter t i)).box

/-- Miss (deficit charge) accumulator, tick-indexed, from zero. -/
def mIter : Nat -> Nat -> Nat
  | 0, _ => 0
  | t + 1, i => mIter t i + (tickFlow i (bIter t i)).miss

/-- Refusal (excess charge) accumulator, tick-indexed, from zero. -/
def rIter : Nat -> Nat -> Nat
  | 0, _ => 0
  | t + 1, i => rIter t i + (tickFlow i (bIter t i)).refused

/-- Sunk accumulator, tick-indexed, from an all-zero start. -/
def sIter : Nat -> Nat -> Nat
  | 0, _ => 0
  | t + 1, i => sIter t i + (tickFlow i (bIter t i)).sunk

/-- Master depth profile: the delayed cycles hover at one, everything
else rests at zero. -/
def fbox (i : Nat) : Nat := if i = 10 ∨ i = 17 then 1 else 0

/-- Per-tick sink profile: exactly the sink flows drain one event. -/
def fsinkone (i : Nat) : Nat := if i = 2 ∨ i = 4 ∨ i = 5 then 1 else 0

theorem fbox_zero {i : Nat} (h10 : i ≠ 10) (h17 : i ≠ 17) : fbox i = 0 := by
  rw [fbox, if_neg (by simp [h10, h17])]

theorem fbox_le : ∀ i : Nat, fbox i ≤ 1 := by
  intro i
  simp only [fbox]
  split <;> omega
"""


